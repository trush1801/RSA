# PART 2: BASELINE CNN MODEL

class CNN(nn.Module):

    def __init__(self):
        super(CNN, self).__init__()

        # Two convolution layers
        self.conv1 = nn.Conv2d(1, 32, 3, padding=1)
        self.conv2 = nn.Conv2d(32, 64, 3, padding=1)

        self.pool = nn.MaxPool2d(2, 2)

        # Two fully connected layers
        self.fc1 = nn.Linear(64 * 7 * 7, 128)
        self.fc2 = nn.Linear(128, 10)

        self.relu = nn.ReLU()

    def forward(self, x):

        x = self.pool(self.relu(self.conv1(x)))
        x = self.pool(self.relu(self.conv2(x)))

        x = x.view(x.size(0), -1)

        x = self.relu(self.fc1(x))
        x = self.fc2(x)

        return x


# Create model
model = CNN().to(device)

# Loss function
criterion = nn.CrossEntropyLoss()

# Adam optimizer
optimizer = optim.Adam(model.parameters(), lr=0.001)


# Train baseline model
print("Training Baseline CNN...")

for epoch in range(2):

    model.train()
    running_loss = 0

    for images, labels in train_loader:

        images = images.to(device)
        labels = labels.to(device)

        optimizer.zero_grad()

        outputs = model(images)

        loss = criterion(outputs, labels)

        loss.backward()

        optimizer.step()

        running_loss += loss.item()

    print(
        f"Epoch {epoch+1}/2, Loss: "
        f"{running_loss/len(train_loader):.4f}"
    )


# Function to calculate accuracy
def evaluate(model, loader):

    model.eval()

    correct = 0
    total = 0

    with torch.no_grad():

        for images, labels in loader:

            outputs = model(images)

            predictions = outputs.argmax(dim=1)

            correct += (predictions == labels).sum().item()
            total += labels.size(0)

    return 100 * correct / total


# Clean test accuracy
clean_accuracy = evaluate(model, test_loader)

print("Clean Test Accuracy:", round(clean_accuracy, 2), "%")

# PART 3: FGSM AND PGD ATTACKS

# FGSM ATTACK
def fgsm_attack(model, images, labels, epsilon):

    images = images.clone().detach().requires_grad_(True)

    outputs = model(images)

    loss = criterion(outputs, labels)

    model.zero_grad()

    gradients = torch.autograd.grad(
        loss, images
    )[0]

    # Add perturbation
    adv_images = images + epsilon * gradients.sign()

    # Keep pixels between 0 and 1
    adv_images = torch.clamp(adv_images, 0, 1)

    return adv_images.detach()


# PGD ATTACK
def pgd_attack(model, images, labels, epsilon,
               alpha=None, steps=10):

    original_images = images.clone().detach()

    if epsilon == 0:
        return original_images

    if alpha is None:
        alpha = epsilon / 4

    # Random start
    adv_images = original_images + torch.empty_like(
        original_images
    ).uniform_(-epsilon, epsilon)

    adv_images = torch.clamp(adv_images, 0, 1)

    # 10 PGD iterations
    for _ in range(steps):

        adv_images = adv_images.detach().requires_grad_(True)

        outputs = model(adv_images)

        loss = criterion(outputs, labels)

        model.zero_grad()

        gradients = torch.autograd.grad(
            loss, adv_images
        )[0]

        adv_images = adv_images.detach() + alpha * gradients.sign()

        # Project into epsilon range
        delta = adv_images - original_images

        delta = torch.clamp(
            delta, -epsilon, epsilon
        )

        adv_images = torch.clamp(
            original_images + delta, 0, 1
        ).detach()

    return adv_images


# Evaluate adversarial accuracy
def attack_accuracy(model, loader, attack_name, epsilon):

    model.eval()

    correct = 0
    total = 0

    for images, labels in loader:

        if attack_name == "FGSM":

            adv_images = fgsm_attack(
                model, images, labels, epsilon
            )

        elif attack_name == "PGD":

            adv_images = pgd_attack(
                model, images, labels, epsilon,
                steps=10
            )

        else:
            adv_images = images

        with torch.no_grad():

            outputs = model(adv_images)

            predictions = outputs.argmax(dim=1)

            correct += (predictions == labels).sum().item()

            total += labels.size(0)

    return 100 * correct / total


